/** localStorage key holding the recently used emoji (newest first). */
export const EMOJI_RECENT_KEY = 'page48:emoji:recent';
export const EMOJI_RECENT_LIMIT = 16;

/** Search across every category by label and aliases. */
export function searchEmojis(query: string): Emoji[] {
	const q = query.trim().toLowerCase();
	if (!q) return [];

	const found = EMOJI_CATEGORIES.flatMap((category) => category.emojis).filter((emoji) => {
		const haystack = `${emoji.label} ${emoji.aliases ?? ''}`.toLowerCase();
		return haystack.includes(q);
	});

	// Results are rendered in one keyed list, so keep a single entry per glyph.
	return [...new Map(found.map((emoji) => [emoji.char, emoji])).values()];
}
