/**
 * Curated emoji set used by the Page48 emoji picker.
 *
 * Kept as local data instead of a picker library so the picker needs no extra
 * dependency and never fetches emoji data from a CDN.
 */

export interface Emoji {
	/** The emoji glyph, e.g. "😀". */
	char: string;
	/** English label, used as the tooltip and the search haystack. */
	label: string;
	/** Extra search terms (e.g. Indonesian equivalents). */
	aliases?: string;
}

export interface EmojiCategory {
	/** Also the i18n key suffix: `page48.emoji.<id>`. */
	id: string;
	/** Glyph shown on the category tab. */
	icon: string;
	emojis: Emoji[];
}

